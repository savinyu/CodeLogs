// Run: pnpm sheets:neetcode. Dev-only; the app never fetches this at runtime.
import { writeFileSync } from "node:fs";

const SOURCE = "https://raw.githubusercontent.com/neetcode-gh/leetcode/main/.problemSiteData.json";
const OUT = new URL("../../lib/sheets/neetcode-data.ts", import.meta.url);

interface Raw {
  problem: string;
  pattern: string;
  link: string;
  difficulty: string;
  neetcode150?: boolean;
  blind75?: boolean;
  premium?: boolean;
}

const res = await fetch(SOURCE, { headers: { "User-Agent": "LogN/0.1" } });
if (!res.ok) throw new Error(`HTTP ${res.status} from ${SOURCE}`);
const raw = (await res.json()) as Raw[];
const rows = raw
  .filter((p) => p.neetcode150)
  .map((p) => {
    const slug = p.link.replace(/\/+$/, "");
    if (!/^[a-z0-9-]+$/.test(slug)) throw new Error(`Unexpected link: ${p.link}`);
    if (!["Easy", "Medium", "Hard"].includes(p.difficulty)) {
      throw new Error(`Unexpected difficulty for ${slug}: ${p.difficulty}`);
    }
    return {
      slug,
      title: p.problem,
      section: p.pattern,
      difficulty: p.difficulty,
      blind75: p.blind75 === true,
      premium: p.premium === true,
    };
  });
const blind = rows.filter((r) => r.blind75).length;
if (rows.length !== 150 || blind !== 75) {
  throw new Error(`Expected 150 / 75 problems, got ${rows.length} / ${blind}`);
}

const header = `// Generated by scripts/dev/sheets-neetcode.ts from ${SOURCE}
// on ${new Date().toISOString().slice(0, 10)}. Don't edit by hand; rerun \`pnpm sheets:neetcode\`.
//
// Problem list from https://github.com/neetcode-gh/leetcode
// MIT License. Copyright (c) 2022 neetcode-gh. Permission is hereby granted, free of charge, to
// any person obtaining a copy of this software and associated documentation files, to deal in
// the Software without restriction, subject to including this notice. THE SOFTWARE IS PROVIDED
// "AS IS", WITHOUT WARRANTY OF ANY KIND. Full text: lib/sheets/NEETCODE_LICENSE.

import type { NeetcodeProblem } from "./types";

/** NeetCode 150 in NeetCode's order; \`blind75\` marks the Blind 75 subset. */
export const NEETCODE_PROBLEMS: readonly NeetcodeProblem[] = `;
writeFileSync(OUT, `${header}${JSON.stringify(rows, null, 2)};\n`);
console.log(`Wrote ${rows.length} problems (${blind} Blind 75) to ${OUT.pathname}`);
